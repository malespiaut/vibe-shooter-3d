int font_pixel(char c, int x, int y)
{
    if (c >= 'a' && c <= 'z') c = (char)(c - 32);
    if (c < 32 || c > 95 || x < 0 || x > 4 || y < 0 || y > 6) return 0;
    return (glyphs[c - 32][y] >> (4 - x)) & 1;
}

int font_width(const char *s, int scale)
{
    int n = 0;
    while (*s++) n++;
    return n * 6 * scale;
}

static void draw_one(uint8_t *fb, int x, int y, const char *s, uint8_t color, int scale)
{
    for (; *s; s++, x += 6 * scale)
        for (int gy = 0; gy < 7 * scale; gy++)
            for (int gx = 0; gx < 5 * scale; gx++) {
                int px = x + gx, py = y + gy;
                if (px < 0 || py < 0 || px >= SCREENW || py >= SCREENH) continue;
                if (font_pixel(*s, gx / scale, gy / scale)) fb[py * SCREENW + px] = color;
            }
}

void font_draw(uint8_t *fb, int x, int y, const char *s, uint8_t color, int scale, int shadow)
{
    if (shadow) draw_one(fb, x + scale, y + scale, s, 0, scale);
    draw_one(fb, x, y, s, color, scale);
}

void font_draw_center(uint8_t *fb, int y, const char *s, uint8_t color, int scale)
{
    font_draw(fb, (SCREENW - font_width(s, scale) + scale) / 2, y, s, color, scale, 1);
}
